#!/usr/bin/env node
// Generates trace.md: each identifier with its level, its checks and the verdict on each build.
//   node tools/trace.mjs [--package .] [--results out/results-web.json,out/results-terminal.json] [--out trace.md]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { identifiers, readPackage } from "./lib/model.mjs";

const { values: o } = parseArgs({
  options: {
    package: { type: "string", default: "." },
    results: { type: "string", default: "out/results-web.json,out/results-terminal.json" },
    out: { type: "string", default: "trace.md" },
  },
});

const model = readPackage(o.package);
const builds = [];
for (const file of o.results.split(",")) {
  if (!existsSync(file)) continue;
  const r = JSON.parse(readFileSync(file, "utf8"));
  builds.push({ name: r.build, byId: new Map(r.results.map((x) => [x.id, x.outcome])) });
}

/** The verdict of one identifier on one build, from the scenarios that verify it. */
function verdict(checks, build) {
  const seen = checks.map((c) => build.byId.get(c)).filter(Boolean);
  if (!seen.length) return "not run";
  if (seen.includes("failed")) return "failed";
  if (seen.includes("passed")) return "passed";
  return "inapplicable";
}

const rows = [];
for (const x of identifiers(model)) {
  if (x.kind === "entry") continue;
  const checks = model.scenarios
    .filter((s) => s.verifies.some((v) => v === x.id || (x.kind === "table" && v.startsWith(`${x.id}.`))))
    .map((s) => s.id);
  if (x.kind === "row" && !checks.length) continue;
  let how = checks.join(", ");
  if (x.kind === "commitment") how = /Check: (\w+)/.exec(model.commitments.find((c) => c.id === x.id).body)?.[1] ?? "";
  const cells = builds.map((b) => (x.kind === "commitment" ? "by its check method" : verdict(checks, b)));
  rows.push(`| ${x.id} | ${x.level ?? ""} | ${x.kind} | ${how || "none"} | ${cells.join(" | ")} |`);
}

const head = ["Identifier", "Level", "Kind", "Checks", ...builds.map((b) => `Verdict: ${b.name}`)];
const must = identifiers(model).filter((x) => x.level === "must" && !["row", "entry", "commitment"].includes(x.kind));
const lines = [
  "# Trace",
  "",
  "This file is generated by `tools/trace.mjs`. Do not edit it.",
  "",
  `The package has ${must.length} must-level identifiers and ${model.scenarios.length} public scenarios.`,
  "A table row is listed only if a scenario cites that row.",
  "",
  `| ${head.join(" | ")} |`,
  `| ${head.map(() => "---").join(" | ")} |`,
  ...rows,
  "",
];
writeFileSync(o.out, lines.join("\n"));
console.log(`${o.out}: ${rows.length} identifiers, ${builds.length} builds`);
